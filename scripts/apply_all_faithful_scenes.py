# Helper to replace a scene block by ID
def replace_scene(code, scene_id, new_block):
    pattern = rf"scenes\.push\(\{{\s*ID:\s*'{scene_id}'[\s\S]*?\n\}}\);"
    if not re.search(pattern, code):
        raise ValueError(f"Scene ID '{scene_id}' not found in code")
    return re.sub(pattern, new_block.strip(), code, count=1)

